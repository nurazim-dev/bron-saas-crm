export function getPublicLangFromCookie(): PublicLang {
  if (typeof document === 'undefined') return 'ru';
  const match = /(?:^|;\s*)zapis_lang=(ru|ky|en)(?:;|$)/.exec(document.cookie);
  if (match?.[1] === 'ky') return 'ky';
  if (match?.[1] === 'en') return 'en';
  return 'ru';
}

export function setPublicLangCookie(lang: PublicLang): void {
  if (typeof document === 'undefined') return;
  document.cookie = `zapis_lang=${lang}; path=/; max-age=31536000; SameSite=Lax`;
  document.documentElement.lang = lang;
}

export function formatPublicDate(isoOrYmd: string, timezone: string, lang: PublicLang): string {
  const dt = isoOrYmd.includes('T')
    ? DateTime.fromISO(isoOrYmd, { zone: 'utc' }).setZone(timezone)
    : DateTime.fromISO(isoOrYmd, { zone: timezone });
  if (lang === 'ky')
    return `${dt.day} ${['январь', 'февраль', 'март', 'апрель', 'май', 'июнь', 'июль', 'август', 'сентябрь', 'октябрь', 'ноябрь', 'декабрь'][dt.month - 1]}, ${['дүйшөмбү', 'шейшемби', 'шаршемби', 'бейшемби', 'жума', 'ишемби', 'жекшемби'][dt.weekday - 1]}`;
  if (lang === 'en') return dt.setLocale('en').toFormat('d LLLL, cccc');
  return dt.setLocale('ru').toFormat('d LLLL, cccc');
}
